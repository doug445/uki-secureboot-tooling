#!/usr/bin/env bash
# Round 2 — post-diagnostic fixes for 2026-04-21 hardening rollout.
# Run from root shell: bash /home/will/fix-postreboot-2.sh
# Only does the safe fixes; flags decisions back to user.

set +e
LOG=/home/will/fix-report-2.txt
exec > >(tee "$LOG") 2>&1

C_BOLD=$'\e[1m'; C_OK=$'\e[32m'; C_WARN=$'\e[33m'; C_BAD=$'\e[31m'; C_RESET=$'\e[0m'
section() { printf '\n%s=== %s ===%s\n' "$C_BOLD" "$1" "$C_RESET"; }
fix()  { printf '  %s[fix]%s %s\n' "$C_WARN" "$C_RESET" "$1"; }
pass() { printf '  %s[ok]%s %s\n'  "$C_OK"   "$C_RESET" "$1"; }
fail() { printf '  %s[!!]%s %s\n'  "$C_BAD"  "$C_RESET" "$1"; }

if [[ $EUID -ne 0 ]]; then
    echo "must be root"
    exit 1
fi

printf '%sRound 2 — %s%s\n' "$C_BOLD" "$(date '+%Y-%m-%d %H:%M %Z')" "$C_RESET"

# ---------- 1. Reset faillock (THE sudo blocker) ----------
section "1. Reset faillock for will (the sudo blocker)"
echo "--- pre-reset tally ---"
faillock --user will
fix "resetting faillock counter for will"
faillock --user will --reset
echo "--- post-reset tally ---"
faillock --user will
pass "sudo should work again from will's shell now. Test: open new terminal, 'sudo -v'"

# ---------- 2. Confirm pwfeedback didn't come back ----------
section "2. pwfeedback regression check"
if grep -rn pwfeedback /etc/sudoers /etc/sudoers.d/ 2>/dev/null; then
    fail "pwfeedback present somewhere — remove it"
else
    pass "no pwfeedback anywhere"
fi

# ---------- 3. audit-rules: real diagnosis ----------
section "3. audit-rules real fix"
echo "--- /etc/audit/audit.rules (generated by augenrules) ---"
cat -n /etc/audit/audit.rules 2>&1 | head -30
echo "--- running augenrules (regenerates /etc/audit/audit.rules) ---"
augenrules 2>&1
echo "--- attempt load ---"
augenrules --load 2>&1
echo "--- service restart ---"
systemctl reset-failed audit-rules.service 2>&1
systemctl start audit-rules.service 2>&1
sleep 1
if systemctl is-active --quiet audit-rules.service; then
    pass "audit-rules.service now active"
else
    fix "audit-rules still failing → disabling for now (auditd itself still runs)"
    systemctl disable audit-rules.service 2>&1
    systemctl reset-failed audit-rules.service 2>&1
    echo "auditd itself:"
    systemctl is-active auditd.service
fi

# ---------- 4. Disable snapd (Manjaro + snap AppArmor mismatch) ----------
section "4. Disable snapd (not our hardening — Manjaro kernel missing snap AA patches)"
systemctl disable --now snapd.service snapd.socket snapd.seeded.service snapd.apparmor.service 2>&1
systemctl reset-failed snapd.service snapd.socket 2>/dev/null

# ---------- 5. NVIDIA module signing diagnosis ----------
section "5. nvidia + sig_enforce diagnosis"
echo "--- is nvidia loaded? ---"
lsmod | grep -i '^nvidia\|^nouveau' || echo "  (neither nvidia nor nouveau currently in lsmod — graphics via something else?)"
echo "--- mhwd-gpu.conf (autoload list) ---"
cat /etc/modules-load.d/mhwd-gpu.conf
echo "--- current nvidia module signature metadata ---"
for mod in nvidia nvidia_drm nvidia_modeset; do
    printf "  %s: " "$mod"
    modinfo "$mod" 2>/dev/null | grep -E '^(sig_id|signer|sig_key|sig_hashalgo):' | tr '\n' '|' || echo "(no modinfo)"
    echo
done
echo "--- kernel trusted keyrings (which keys CAN sign modules) ---"
cat /proc/keys 2>/dev/null | grep -E 'keyring.*(builtin|machine|platform|secondary)' | head
echo "--- kernel config for MOK trust (need these = y for DKMS/MOK modules under sig_enforce) ---"
zcat /proc/config.gz 2>/dev/null | grep -E 'CONFIG_INTEGRITY_MOK_KEYRING|CONFIG_SECONDARY_TRUSTED_KEYRING|CONFIG_MODULE_SIG|CONFIG_INTEGRITY_PLATFORM_KEYRING' || \
cat /boot/config-$(uname -r) 2>/dev/null | grep -E 'CONFIG_INTEGRITY_MOK_KEYRING|CONFIG_SECONDARY_TRUSTED_KEYRING|CONFIG_MODULE_SIG|CONFIG_INTEGRITY_PLATFORM_KEYRING'
echo
echo "DECISION PATHS (do not auto-fix):"
echo "  (a) If INTEGRITY_MOK_KEYRING=y AND the signer= line is empty or 'DKMS module signing key',"
echo "      the signing happened but the key isn't trusted. Re-sign with a key in .machine, or"
echo "      re-enroll the MOK using mokutil."
echo "  (b) If INTEGRITY_MOK_KEYRING is not y (Manjaro may not ship that config), sig_enforce"
echo "      can't trust any MOK-signed module. Either drop sig_enforce=1 (keep lockdown=integrity —"
echo "      still A-grade lockdown), or switch to a kernel that enables the MOK keyring."
echo "  (c) Comment out the 'nvidia' lines from /etc/modules-load.d/mhwd-gpu.conf so"
echo "      systemd-modules-load stops failing. X/Wayland will fall back to nouveau."

# ---------- 6. usbguard-lock-hook: diagnose why it didn't start ----------
section "6. usbguard-lock-hook diagnosis"
echo "--- unit file (first 40 lines) ---"
head -40 /home/will/.config/systemd/user/usbguard-lock-hook.service
echo "--- is it enabled? ---"
ls -la /home/will/.config/systemd/user/default.target.wants/usbguard-lock-hook.service 2>&1
echo "--- user daemon reload + try start ---"
runuser -u will -- env XDG_RUNTIME_DIR=/run/user/1000 DBUS_SESSION_BUS_ADDRESS=unix:path=/run/user/1000/bus \
    systemctl --user daemon-reload 2>&1
runuser -u will -- env XDG_RUNTIME_DIR=/run/user/1000 DBUS_SESSION_BUS_ADDRESS=unix:path=/run/user/1000/bus \
    systemctl --user start usbguard-lock-hook.service 2>&1
sleep 2
runuser -u will -- env XDG_RUNTIME_DIR=/run/user/1000 DBUS_SESSION_BUS_ADDRESS=unix:path=/run/user/1000/bus \
    systemctl --user status usbguard-lock-hook.service --no-pager -n 20 2>&1 | head -30
echo "--- hook log this boot ---"
runuser -u will -- env XDG_RUNTIME_DIR=/run/user/1000 DBUS_SESSION_BUS_ADDRESS=unix:path=/run/user/1000/bus \
    journalctl --user -u usbguard-lock-hook.service -b 0 --no-pager 2>&1 | tail -30

# ---------- 7. Cinnamon daemon crashes (context only) ----------
section "7. csd-media-keys crash details"
coredumpctl info 4012 2>&1 | sed -n '1,40p'

# ---------- Summary ----------
section "AFTER ROUND 2 — failed units"
systemctl --failed --no-legend

echo
echo "[round 2 report saved to $LOG]"
